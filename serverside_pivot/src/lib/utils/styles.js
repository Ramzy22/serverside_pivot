/** @param {any} [theme] @returns {any} */
export const isDarkTheme = (theme) => theme && (theme.name === 'dark' || theme.isDark === true);

/** @param {any} [value] @returns {any} */
const isPlainObject = (value) => Boolean(value) && typeof value === 'object' && !Array.isArray(value);

/** @param {any} [value] @param {any} [fallback] @returns {any} */
export const toCssPx = (value, fallback) => {
    if (typeof value === 'number' && Number.isFinite(value)) return `${value}px`;
    if (typeof value === 'string' && value.trim()) {
        /** @type {any} */
        const trimmed = value.trim();
        return /^-?\d+(\.\d+)?$/.test(trimmed) ? `${trimmed}px` : trimmed;
    }
    return fallback;
};

/** @param {any} [value] @param {any} [fallback] @returns {any} */
export const toFiniteNumber = (value, fallback = null) => {
    if (typeof value === 'number' && Number.isFinite(value)) return value;
    if (typeof value === 'string' && value.trim()) {
        /** @type {any} */
        const parsed = Number.parseFloat(value.trim());
        if (Number.isFinite(parsed)) return parsed;
    }
    return fallback;
};

/** @param {any} [tokenValue] @param {any} [depth] @param {any} [fallback] @returns {any} */
export const resolveDepthToken = (tokenValue, depth = 0, fallback = undefined) => {
    if (Array.isArray(tokenValue)) {
        if (tokenValue.length === 0) return fallback;
        /** @type {any} */
        const safeDepth = Number.isFinite(Number(depth)) ? Math.max(0, Math.floor(Number(depth))) : 0;
        const value = tokenValue[Math.min(safeDepth, tokenValue.length - 1)];
        return value !== undefined && value !== null ? value : fallback;
    }
    return tokenValue !== undefined && tokenValue !== null ? tokenValue : fallback;
};

/** @param {any} [themeName] @param {any} [rawOverrides] @returns {any} */
export const resolveThemeOverrides = (themeName, rawOverrides) => {
    if (!isPlainObject(rawOverrides)) return {};
    /** @type {any} */
    const knownThemeNames = new Set(Object.keys(themes));
    /** @type {Record<string, any>} */
    const flatOverrides = {};
    Object.entries(rawOverrides).forEach(([key, value]) => {
        if (knownThemeNames.has(key) && isPlainObject(value)) return;
        if (value !== undefined) flatOverrides[key] = value;
    });
    /** @type {any} */
    const perTheme = themeName && isPlainObject(rawOverrides[themeName])
        ? rawOverrides[themeName]
        : {};
    return {
        ...flatOverrides,
        ...perTheme,
    };
};

/** @param {any} [theme] @returns {any} */
export const resolveGridLineBorders = (theme) => {
    /** @type {any} */
    const mode = String((theme && theme.gridLines) || 'both').toLowerCase();
    /** @type {any} */
    const showH = mode === 'both' || mode === 'horizontal';
    /** @type {any} */
    const showV = mode === 'both' || mode === 'vertical';
    /** @type {any} */
    const baseBorder = (theme && theme.border) || '#e0e0e0';
    /** @type {any} */
    const rowBorderColor = showH ? ((theme && theme.rowBorder) || baseBorder) : 'transparent';
    /** @type {any} */
    const columnBorderColor = showV ? ((theme && theme.columnBorder) || baseBorder) : 'transparent';
    /** @type {any} */
    const headerBorderBottomColor = (theme && (theme.headerBorderBottom || theme.borderStrong || theme.border)) || baseBorder;
    /** @type {any} */
    const pinnedColumnBorderColor = (theme && (theme.pinnedColumnBorder || theme.borderStrong || theme.border)) || baseBorder;
    return {
        mode,
        showH,
        showV,
        rowBorderColor,
        columnBorderColor,
        headerBorderBottomColor,
        pinnedColumnBorderColor,
    };
};

